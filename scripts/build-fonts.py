#!/usr/bin/env python3
"""Builds fonts/*.woff2 and css/fonts.css from the Fontsource npm packages (all SIL OFL).

    npm i --no-save @fontsource-variable/fraunces @fontsource-variable/inter \
        @fontsource/hind @fontsource/hind-siliguri @fontsource/tiro-devanagari-hindi @fontsource/tiro-bangla
    pip install fonttools brotli
    python3 scripts/build-fonts.py            # reads ./node_modules

Why a script and not just downloaded files: the app only needs a slice of each family, and the slicing is easy to
get wrong by hand. In particular the rupee sign (U+20B9) lives in "latin-ext", so a plain "latin" download would
quietly show it in a system font.
"""
import re, shutil, sys
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
NM = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / 'node_modules')
OUT = ROOT / 'fonts'
CURRENCY = 'U+20A0-20C0'  # includes the rupee sign
OUT.mkdir(exist_ok=True); (OUT / 'licenses').mkdir(exist_ok=True)

def save(font, name):
    font.flavor = 'woff2'; font.save(OUT / name); print(f'  {name:34s}{(OUT / name).stat().st_size / 1024:6.1f} KB')

def variable(pkg, file, limits, name, unicodes=None):
    f = TTFont(NM / '@fontsource-variable' / pkg / 'files' / file)
    f = instancer.instantiateVariableFont(f, limits)  # pin or narrow axes the app never uses
    if unicodes:
        opts = subset.Options(); opts.layout_features = ['*']; opts.flavor = 'woff2'
        s = subset.Subsetter(opts); s.populate(unicodes=subset.parse_unicodes(unicodes)); s.subset(f)
    save(f, name)

def unicode_range(css_file, comment):
    css = Path(css_file).read_text(encoding='utf-8')
    block = css[css.index(f'/* {comment} */'):]
    return re.search(r'unicode-range:\s*([^;]+);', block).group(1).strip()

faces = []  # (family, weight, file, unicode-range)
print('Fraunces (opsz + wght 400-600 + SOFT; WONK pinned off)')
fr = NM / '@fontsource-variable/fraunces'
variable('fraunces', 'fraunces-latin-full-normal.woff2', {'wght': (400, 600), 'WONK': 0}, 'fraunces-latin.woff2')
variable('fraunces', 'fraunces-latin-ext-full-normal.woff2', {'wght': (400, 600), 'WONK': 0}, 'fraunces-currency.woff2', CURRENCY)
faces += [('Fraunces', '400 600', 'fraunces-latin.woff2', unicode_range(fr / 'full.css', 'fraunces-latin-full-normal')),
          ('Fraunces', '400 600', 'fraunces-currency.woff2', CURRENCY)]

print('Inter (wght 400-700)')
it = NM / '@fontsource-variable/inter'
variable('inter', 'inter-latin-wght-normal.woff2', {'wght': (400, 700)}, 'inter-latin.woff2')
variable('inter', 'inter-latin-ext-wght-normal.woff2', {'wght': (400, 700)}, 'inter-currency.woff2', CURRENCY)
faces += [('Inter', '400 700', 'inter-latin.woff2', unicode_range(it / 'index.css', 'inter-latin-wght-normal')),
          ('Inter', '400 700', 'inter-currency.woff2', CURRENCY)]

print('Indic families (copied as published)')
def static(pkg, fam, short, subset_name, weight):
    src = NM / '@fontsource' / pkg / 'files' / f'{pkg}-{subset_name}-{weight}-normal.woff2'
    dst = f'{short}-{subset_name}-{weight}.woff2'
    shutil.copy(src, OUT / dst); print(f'  {dst:34s}{src.stat().st_size / 1024:6.1f} KB')
    faces.append((fam, str(weight), dst, unicode_range(NM / '@fontsource' / pkg / f'{weight}.css', f'{pkg}-{subset_name}-{weight}-normal')))
for w in (400, 500, 600):
    static('hind', 'Hind', 'hind', 'devanagari', w)
for w in (400, 500, 600):
    static('hind-siliguri', 'Hind Siliguri', 'hind-siliguri', 'bengali', w)
for s in ('devanagari', 'latin'):
    static('tiro-devanagari-hindi', 'Tiro Devanagari Hindi', 'tiro-devanagari-hindi', s, 400)
for s in ('bengali', 'latin'):
    static('tiro-bangla', 'Tiro Bangla', 'tiro-bangla', s, 400)

# Licences must travel with the fonts (SIL OFL).
for pkg in ['@fontsource-variable/fraunces', '@fontsource-variable/inter', '@fontsource/hind', '@fontsource/hind-siliguri',
            '@fontsource/tiro-devanagari-hindi', '@fontsource/tiro-bangla']:
    shutil.copy(NM / pkg / 'LICENSE', OUT / 'licenses' / f'{pkg.split("/")[1]}.txt')

css = ['/* Self-hosted fonts. Generated by scripts/build-fonts.py: edit the script, not this file.',
       '   Rarely used scripts load only when a page shows them (unicode-range). */']
for fam, weight, file, ur in faces:
    css.append(f"@font-face{{font-family:'{fam}';font-style:normal;font-weight:{weight};font-display:swap;src:url(../fonts/{file}) format('woff2');unicode-range:{ur}}}")
(ROOT / 'css' / 'fonts.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
total = sum(p.stat().st_size for p in OUT.glob('*.woff2')) / 1024
print(f'\n{len(faces)} faces, {total:.0f} KB total -> fonts/ and css/fonts.css')
